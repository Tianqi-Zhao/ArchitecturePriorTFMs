"""Render the controlled-experiment paper figures from a portable data folder."""

import argparse
import hashlib
import json
from pathlib import Path

from .data import load_bundle


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument("--data-dir", type=Path, required=True,
                        help="plotting-data directory generated by paper_figures.summarize")
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--only", choices=("baselines", "interventions", "ols"), nargs="+",
                        default=["baselines", "interventions", "ols"])
    parser.add_argument("--formats", choices=("pdf", "png", "svg"), nargs="+", default=["pdf", "png"])
    args = parser.parse_args(argv)
    try:
        bundle, manifest = load_bundle(args.data_dir)
    except (ValueError, KeyError, FileNotFoundError) as error:
        parser.error(str(error))
    # Plotting imports stay after argument parsing so --help has no GUI side effects.
    from . import baselines, interventions, ols
    from .render import Renderer
    renderer = Renderer(args.output_dir, formats=tuple(dict.fromkeys(args.formats)))
    for family in dict.fromkeys(args.only):
        {"baselines": baselines, "interventions": interventions, "ols": ols}[family].build(bundle, renderer)
    output = {
        "schema_version": 1, "data_files_sha256": manifest["files"],
        "formats": renderer.formats, "families": renderer.families, "extra_files": renderer.extras,
        "code_sha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                        for p in sorted(Path(__file__).parent.glob("*.py"))},
        "note": "Fresh vector drawings from the published statistics; typography is not a byte-for-byte PDF copy.",
    }
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "figure_manifest.json").write_text(json.dumps(output, indent=2) + "\n")
    count = sum(len(f["panels"]) for f in renderer.families.values())
    print(f"Rendered {len(renderer.families)} figure families / {count} independent panels to {args.output_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
