from torch.utils.data import DataLoader
import h5py
import torch
import numpy as np
from utils import get_default_device


def _shared_train_test_split_index(
    split_indices: np.ndarray,
    *,
    pointer_start: int,
    pointer_end: int,
) -> int:
    """Return the batch split after verifying every episode shares it."""

    split_indices = np.asarray(split_indices)
    first = int(split_indices[0])
    if not np.all(split_indices == first):
        raise ValueError(
            "All episodes in a prior batch must share train_test_split_index; "
            f"rows [{pointer_start}, {pointer_end}) contain "
            f"single_eval_pos={split_indices.tolist()}"
        )
    return first


def table_padding_masks(
    batch: dict,
    *,
    device: torch.device | None = None,
) -> tuple[torch.Tensor | None, torch.Tensor | None]:
    """Build row and feature padding masks from a prior batch.

    ``True`` marks padding. Feature pads are taken from ``feature_padding_mask``
    when the loader already shuffled columns; otherwise they are reconstructed
    as trailing zeros from per-table ``num_features``. An all-false feature
    mask is returned as ``None`` so homogeneous-``d`` batches keep the unmasked
    attention path.
    """
    x = batch["x"]
    if device is None:
        device = x.device
    padding_mask = None
    if "num_datapoints" in batch:
        num_dp = batch["num_datapoints"].to(device)
        padding_mask = (
            torch.arange(x.shape[1], device=device).unsqueeze(0) >= num_dp.unsqueeze(1)
        )
    feature_padding_mask = None
    raw = batch.get("feature_padding_mask")
    if raw is not None:
        feature_padding_mask = raw.to(device=device, dtype=torch.bool)
    elif "num_features" in batch:
        num_feat = batch["num_features"].to(device)
        feature_padding_mask = (
            torch.arange(x.shape[2], device=device).unsqueeze(0)
            >= num_feat.unsqueeze(1)
        )
    if feature_padding_mask is not None and not bool(feature_padding_mask.any()):
        feature_padding_mask = None
    return padding_mask, feature_padding_mask


def resolve_pointer_region(
    n_rows: int,
    pointer_start: int,
    pointer_end: int | None,
    batch_size: int,
) -> tuple[int, int]:
    """Validate the loader's [start, end) region against the dump length."""

    pointer_start = int(pointer_start)
    resolved_end = n_rows if pointer_end is None else int(pointer_end)
    if pointer_start < 0:
        raise ValueError(f"pointer_start={pointer_start} must be >= 0")
    if resolved_end > n_rows:
        raise ValueError(
            f"pointer_end={resolved_end} exceeds n_rows={n_rows}; "
            "short batches would be read from the HDF5 dump"
        )
    if resolved_end - pointer_start < batch_size:
        raise ValueError(
            f"Row region [pointer_start={pointer_start}, pointer_end={resolved_end}) "
            f"is smaller than batch_size={batch_size}. "
            "Increase the region or decrease batch_size."
        )
    return pointer_start, resolved_end


class PriorDumpDataLoader(DataLoader):
    """DataLoader that loads synthetic prior data from an HDF5 dump.

    Each batch includes ``num_datapoints`` and a ``(B, C)``
    ``feature_padding_mask`` (True = padded column). Mixed-width tables are
    sliced to the batch-max ``C``; padding columns stay in the tensor so the
    2D / 1DICL models can mask them the same way they mask padded rows.
    Feature shuffle permutes ``x`` and the mask together.

    Args:
        filename (str): Path to the HDF5 file.
        num_steps (int): Number of batches per epoch.
        batch_size (int): Batch size.
        shuffle_features (bool): Whether to randomly permute feature column order each batch.
        device (torch.device): Device to load tensors onto.
        pointer_start (int): First row index (inclusive) this loader is allowed to read.
            Wrapping stays within [pointer_start, pointer_end). Default: 0.
        pointer_end (int | None): One-past-last row index this loader is allowed to read.
            Must not exceed the dump length. Default: None (resolved to X.shape[0]).
    """

    def __init__(self, filename, num_steps, batch_size, shuffle_features=False, device=None,
                 pointer_start: int = 0, pointer_end: int | None = None):
        self.filename = filename
        self.num_steps = num_steps
        self.batch_size = batch_size
        self.shuffle_features = shuffle_features
        if device is None:
            device = get_default_device()
        self.device = device
        with h5py.File(self.filename, "r") as f:
            if "max_num_classes" in f:
                self.max_num_classes = int(f["max_num_classes"][0])
            else:
                # Regression dumps generated by older code may not have this field.
                self.max_num_classes = 1
            n_rows = int(f["X"].shape[0])
        self.pointer_start, self.pointer_end = resolve_pointer_region(
            n_rows, pointer_start, pointer_end, batch_size
        )
        self.pointer = self.pointer_start

    def __iter__(self):
        with h5py.File(self.filename, "r") as f:
            for _ in range(self.num_steps):
                # Wrap within [pointer_start, pointer_end) before reading.
                if self.pointer + self.batch_size > self.pointer_end:
                    self.pointer = self.pointer_start

                end = self.pointer + self.batch_size
                actual_num_features = np.asarray(
                    f["num_features"][self.pointer:end], dtype=np.int64
                )
                max_features = int(actual_num_features.max())
                num_datapoints_batch = f["num_datapoints"][self.pointer:end]
                max_seq_in_batch = int(num_datapoints_batch.max())
                x = f["X"][self.pointer:end, :max_seq_in_batch, :max_features]
                y = f["y"][self.pointer:end, :max_seq_in_batch]
                feature_padding_mask = (
                    np.arange(max_features, dtype=np.int64)[None, :]
                    >= actual_num_features[:, None]
                )

                if self.shuffle_features:
                    perm = np.random.permutation(max_features)
                    x = x[:, :, perm]
                    feature_padding_mask = feature_padding_mask[:, perm]

                x = torch.from_numpy(x.copy())
                y = torch.from_numpy(y.copy())
                train_test_split_indices = f["single_eval_pos"][self.pointer:end]
                train_test_split_index = _shared_train_test_split_index(
                    train_test_split_indices,
                    pointer_start=self.pointer,
                    pointer_end=end,
                )

                self.pointer += self.batch_size

                yield dict(
                    x=x.to(self.device),
                    y=y.to(self.device),
                    train_test_split_index=train_test_split_index,
                    num_datapoints=torch.from_numpy(num_datapoints_batch.copy()),
                    num_features=torch.from_numpy(actual_num_features.copy()),
                    feature_padding_mask=torch.from_numpy(
                        np.ascontiguousarray(feature_padding_mask)
                    ),
                )

    def __len__(self):
        return self.num_steps


class PriorDumpDataLoader1D(DataLoader):
    """DataLoader for the 1D attention model with feature alignment and column shuffling.

    Differences from PriorDumpDataLoader:
        - Aligns all features to a fixed num_features dimension via zero-padding (if fewer)
          or PCA (if more), because the 1D model uses nn.Linear(num_features, E).
        - Optionally shuffles feature column order each batch, because 1D attention is NOT
          permutation invariant over features (unlike 2D attention which has separate
          attention over the feature axis). Shuffling during training teaches the model
          to be robust to arbitrary feature orderings at inference time.

    Args:
        filename (str): Path to the HDF5 file.
        num_steps (int): Number of batches per epoch.
        batch_size (int): Batch size.
        num_features (int): Fixed target feature dimension for the 1D model.
        shuffle_features (bool): Whether to randomly permute column order each batch.
        device (torch.device): Device to load tensors onto.
        pointer_start (int): First row index (inclusive) this loader is allowed to read.
            Wrapping stays within [pointer_start, pointer_end). Default: 0.
        pointer_end (int | None): One-past-last row index this loader is allowed to read.
            Must not exceed the dump length. Default: None (resolved to X.shape[0]).
    """

    def __init__(self, filename, num_steps, batch_size, num_features,
                 shuffle_features=True, device=None,
                 pointer_start: int = 0, pointer_end: int | None = None):
        self.filename = filename
        self.num_steps = num_steps
        self.batch_size = batch_size
        self.num_features = num_features
        self.shuffle_features = shuffle_features
        if device is None:
            device = get_default_device()
        self.device = device
        with h5py.File(self.filename, "r") as f:
            if "max_num_classes" in f:
                self.max_num_classes = int(f["max_num_classes"][0])
            else:
                # Regression dumps generated by older code may not have this field.
                self.max_num_classes = 1
            n_rows = int(f["X"].shape[0])
        self.pointer_start, self.pointer_end = resolve_pointer_region(
            n_rows, pointer_start, pointer_end, batch_size
        )
        self.pointer = self.pointer_start

    def _align_features(self, x_batch, actual_num_features, train_test_split_indices):
        """Align features to self.num_features for each dataset in the batch.

        - If a dataset has fewer features: zero-pad the remaining columns.
        - If a dataset has more features: apply PCA (fitted on training portion only).

        Args:
            x_batch: numpy array (batch_size, max_seq, max_actual_features)
            actual_num_features: numpy array (batch_size,) actual feature count per dataset
            train_test_split_indices: numpy array (batch_size,) split index per dataset
        Returns:
            numpy array (batch_size, max_seq, self.num_features)
        """
        B, S, C = x_batch.shape

        # fast path: all datasets fit within num_features (common case)
        if C <= self.num_features:
            if C == self.num_features:
                return x_batch
            result = np.zeros((B, S, self.num_features), dtype=x_batch.dtype)
            result[:, :, :C] = x_batch
            return result

        # slow path: at least one dataset needs PCA
        from sklearn.decomposition import PCA
        result = np.zeros((B, S, self.num_features), dtype=x_batch.dtype)
        for i in range(B):
            n_feat = int(actual_num_features[i])
            x_i = x_batch[i, :, :n_feat]
            if n_feat <= self.num_features:
                result[i, :, :n_feat] = x_i
            else:
                split_idx = int(train_test_split_indices[i])
                pca = PCA(n_components=self.num_features)
                pca.fit(x_i[:split_idx])
                result[i] = pca.transform(x_i)
        return result

    def __iter__(self):
        with h5py.File(self.filename, "r") as f:
            for _ in range(self.num_steps):
                # Wrap within [pointer_start, pointer_end) before reading.
                if self.pointer + self.batch_size > self.pointer_end:
                    self.pointer = self.pointer_start

                end = self.pointer + self.batch_size
                actual_num_features = f["num_features"][self.pointer:end]
                max_actual = int(actual_num_features.max())
                num_datapoints_batch = f["num_datapoints"][self.pointer:end]
                max_seq_in_batch = int(num_datapoints_batch.max())
                train_test_split_indices = f["single_eval_pos"][self.pointer:end]
                train_test_split_index = _shared_train_test_split_index(
                    train_test_split_indices,
                    pointer_start=self.pointer,
                    pointer_end=end,
                )

                x = f["X"][self.pointer:end, :max_seq_in_batch, :max_actual]
                y = f["y"][self.pointer:end, :max_seq_in_batch]

                # align all features to fixed num_features dimension
                x = self._align_features(x, actual_num_features, train_test_split_indices)

                # shuffle feature column order (same permutation for all samples in batch)
                if self.shuffle_features:
                    perm = np.random.permutation(self.num_features)
                    x = x[:, :, perm]

                x = torch.from_numpy(x.copy())
                y = torch.from_numpy(y.copy())

                self.pointer += self.batch_size

                yield dict(
                    x=x.to(self.device),
                    y=y.to(self.device),
                    train_test_split_index=train_test_split_index,
                    num_datapoints=torch.from_numpy(num_datapoints_batch.copy()),
                )

    def __len__(self):
        return self.num_steps
